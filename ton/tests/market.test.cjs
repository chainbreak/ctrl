const test = require('node:test');
const assert = require('node:assert/strict');
const { Blockchain } = require('@ton/sandbox');
const { beginCell, toNano, Dictionary } = require('@ton/core');
const { createHash } = require('node:crypto');
const p = require('../wrappers/protocol.cjs');

test('TAP purchase, duplicate, forged notification, resale, gift and change', async () => {
  const chain = await Blockchain.create();
  const admin = await chain.treasury('staff'), alice = await chain.treasury('alice'), bob = await chain.treasury('bob');
  const tap = p.master(admin.address);
  const shop = p.collection(admin.address,tap.address,false,toNano('10'));
  const gifts = p.collection(admin.address,tap.address,true,toNano('3'));
  for (const c of [tap,shop,gifts]) await admin.send({to:c.address,init:c.init,value:toNano('1')});
  const getter = async (address,name,args=[]) => (await chain.runGetMethod(address,name,args)).stackReader;
  const credit = async (c,user) => (await getter(c.address,'get_credit',[p.argAddress(user.address)])).readBigNumber();
  const wallet = async user => (await getter(tap.address,'get_wallet_address',[p.argAddress(user.address)])).readAddress();
  const ownerOf = async (c,index) => {
    const item = (await getter(c.address,'get_nft_address_by_index',[{type:'int',value:index}])).readAddress();
    const stack = await getter(item,'get_nft_data');
    assert.ok(stack.readBoolean()); assert.equal(stack.readBigNumber(),index);
    assert.ok(stack.readAddress().equals(c.address));
    return {owner:stack.readAddress(),item,content:stack.readCell()};
  };
  const send = (buyer,to,body,gas='0.2') => buyer.send({to,body,value:toNano(gas)});
  const forged = beginCell().storeUint(0x7362d09c,32).storeUint(0,64).storeCoins(toNano('99'))
    .storeAddress(alice.address).storeBit(0).endCell();
  await send(alice,shop.address,forged); assert.equal(await credit(shop,alice),0n);
  await send(admin,tap.address,p.mint(alice.address,toNano('50')),'0.3');
  const aw = await wallet(alice);
  await send(alice,aw,p.deposit(shop.address,alice.address,toNano('30')));
  assert.equal(await credit(shop,alice),toNano('30'));
  await send(alice,shop.address,p.buy('+99900000001'));
  assert.equal(await credit(shop,alice),toNano('30'));
  const number = '+33300001234', index = p.numberIndex(number);
  await send(alice,shop.address,p.buy(number));
  assert.equal(await credit(shop,alice),toNano('20')); assert.equal(await credit(shop,admin),toNano('10'));
  const {owner,item} = await ownerOf(shop,index); assert.ok(owner.equals(alice.address));
  await send(alice,shop.address,p.buy(number)); assert.equal(await credit(shop,alice),toNano('20'));
  await send(bob,item,p.transferItem(bob.address,bob.address));
  assert.ok((await ownerOf(shop,index)).owner.equals(alice.address));
  await send(alice,item,p.transferItem(bob.address,alice.address));
  assert.ok((await ownerOf(shop,index)).owner.equals(bob.address));
  assert.equal((await getter(item,'get_ownership_version')).readBigNumber(),1n);
  const sliceArg = cell => ({type:'slice',cell});
  const walletCategory = BigInt('0x'+createHash('sha256').update('wallet').digest('hex'));
  const record = await getter(shop.address,'dnsresolve',[sliceArg(beginCell().storeStringTail(number.slice(1)+'\0').endCell()),{type:'int',value:walletCategory}]);
  assert.equal(record.readNumber(),88);
  const delegate = record.readCell().beginParse(); assert.equal(delegate.loadUint(16),0xba93); assert.ok(delegate.loadAddress().equals(item));
  const resolution = await getter(item,'dnsresolve',[sliceArg(beginCell().storeUint(0,8).endCell()),{type:'int',value:walletCategory}]);
  assert.equal(resolution.readNumber(),8); const target = resolution.readCell().beginParse();
  assert.equal(target.loadUint(16),0x9fd3); assert.ok(target.loadAddress().equals(bob.address));
  const details = (await ownerOf(shop,index)).content.beginParse();
  assert.equal(details.loadUint(8),0);
  const fields = details.loadDict(Dictionary.Keys.BigUint(256),Dictionary.Values.Cell());
  const name = fields.get(BigInt('0x'+createHash('sha256').update('name').digest('hex'))).beginParse();
  assert.equal(name.loadUint(8),0); assert.equal(name.loadStringTail(),number);
  await send(admin,shop.address,p.buy('+99900000001'));
  assert.ok((await ownerOf(shop,p.numberIndex('+99900000001'))).owner.equals(admin.address));
  await send(alice,shop.address,p.recover(index));
  assert.ok((await ownerOf(shop,index)).owner.equals(bob.address));
  await send(alice,aw,p.deposit(gifts.address,alice.address,toNano('3')));
  await send(alice,gifts.address,p.buy()); assert.ok((await ownerOf(gifts,0n)).owner.equals(alice.address));
  const withdrawal = await send(alice,shop.address,p.withdraw(toNano('20')));
  const receipt = withdrawal.transactions.find(tx => tx.inMessage?.body.bits.length >= 32 && tx.inMessage.body.beginParse().preloadUint(32) === 0x43545205);
  assert.ok(receipt && !receipt.description.aborted);
  assert.equal(await credit(shop,alice),0n);
  const balance=(await getter(aw,'get_wallet_data')).readBigNumber();
  assert.equal(balance,toNano('37'));
});

